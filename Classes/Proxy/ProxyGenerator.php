namespace KonradMichalik\Typo3Outbound\Proxy;

use KonradMichalik\Typo3Outbound\Exception\InvalidDefinition;
use KonradMichalik\Typo3Outbound\Runtime\EndpointInvoker;
use ReflectionClass;
use ReflectionIntersectionType;
use ReflectionMethod;
use ReflectionNamedType;
use ReflectionParameter;
use ReflectionType;
use ReflectionUnionType;
use UnitEnum;

use function array_map;
use function defined;
use function implode;
use function in_array;
use function is_array;
use function is_object;
use function ltrim;
use function preg_match;
use function sprintf;
use function str_contains;
use function str_starts_with;
use function strpos;
use function strrpos;
use function substr;
use function var_export;

/**
 * ProxyGenerator.
 *
 * Generates the class implementing an API interface. The code only contains
 * names and types taken from reflection; attribute values never reach it, so a
 * declaration can not inject code. Every method delegates to EndpointInvoker.
 *
 * @internal
 *
 * @author Konrad Michalik <hej@konradmichalik.dev>
 */
final class ProxyGenerator
{
    public const VERSION = '1';

    /**
     * @param ReflectionClass<object> $interface
     */
    public function generate(ReflectionClass $interface, string $className): string
    {
        if (1 !== preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $className)) {
            throw new InvalidDefinition(sprintf('Invalid proxy class name "%s".', $className), 1794700160);
        }
        $methods = [];
        foreach ($interface->getMethods() as $method) {
            $methods[] = $this->method($interface, $method);
        }

        return sprintf(
            "<?php\n\ndeclare(strict_types=1);\n\n/** Generated by typo3_outbound for %s. Do not edit. */\nfinal class %s implements \\%s\n{\n    public function __construct(private readonly \\%s \$invoker) {}\n%s}\n",
            $interface->getName(),
            $className,
            $interface->getName(),
            EndpointInvoker::class,
            implode('', $methods),
        );
    }

    /**
     * @param ReflectionClass<object> $interface
     */
    private function method(ReflectionClass $interface, ReflectionMethod $method): string
    {
        $parameters = array_map($this->parameter(...), $method->getParameters());
        $arguments = array_map(static fn (ReflectionParameter $parameter): string => '$'.$parameter->getName(), $method->getParameters());
        $returnType = $method->getReturnType();
        $returnsVoid = $returnType instanceof ReflectionNamedType && 'void' === $returnType->getName();
        $call = sprintf('$this->invoker->call(\\%s::class, %s, [%s])', $method->getDeclaringClass()->getName(), var_export($method->getName(), true), implode(', ', $arguments));

        return sprintf(
            "\n    public function %s(%s)%s\n    {\n        %s;\n    }\n",
            $method->getName(),
            implode(', ', $parameters),
            null !== $returnType ? ': '.$this->type($returnType) : '',
            $returnsVoid ? $call : 'return '.$call,
        );
    }

    private function parameter(ReflectionParameter $parameter): string
    {
        if ($parameter->isPassedByReference() || $parameter->isVariadic()) {
            throw new InvalidDefinition(sprintf('Parameter $%s: by-reference and variadic parameters are not supported.', $parameter->getName()), 1794700161);
        }
        $code = (null !== $parameter->getType() ? $this->type($parameter->getType()).' ' : '').'$'.$parameter->getName();
        if ($parameter->isDefaultValueAvailable()) {
            $code .= ' = '.$this->defaultValue($parameter);
        }

        return $code;
    }

    private function defaultValue(ReflectionParameter $parameter): string
    {
        if ($parameter->isDefaultValueConstant()) {
            $constant = (string) $parameter->getDefaultValueConstantName();
            if (str_starts_with($constant, 'self::') || str_starts_with($constant, 'static::')) {
                // In the generated class `self` is the proxy, not the interface that declares the constant.
                return '\\'.$parameter->getDeclaringClass()?->getName().substr($constant, (int) strpos($constant, '::'));
            }
            if (!str_contains($constant, '::') && str_contains($constant, '\\') && !defined($constant)) {
                // Reflection reports a global constant as seen from the namespace: fall back to the global one.
                return '\\'.substr($constant, (int) strrpos($constant, '\\') + 1);
            }

            return str_contains($constant, '::') || str_contains($constant, '\\') ? '\\'.ltrim($constant, '\\') : '\\'.$constant;
        }
        $value = $parameter->getDefaultValue();
        if ($value instanceof UnitEnum) {
            return '\\'.$value::class.'::'.$value->name;
        }
        if (is_object($value) || (is_array($value) && $this->containsObject($value))) {
            throw new InvalidDefinition(sprintf('Parameter $%s: object default values are not supported in API interfaces.', $parameter->getName()), 1794700162);
        }

        return var_export($value, true);
    }

    /**
     * @param array<array-key, mixed> $value
     */
    private function containsObject(array $value): bool
    {
        foreach ($value as $item) {
            if (is_object($item) || (is_array($item) && $this->containsObject($item))) {
                return true;
            }
        }

        return false;
    }

    private function type(ReflectionType $type): string
    {
        if ($type instanceof ReflectionUnionType) {
            return implode('|', array_map($this->type(...), $type->getTypes()));
        }
        if ($type instanceof ReflectionIntersectionType) {
            return '('.implode('&', array_map($this->type(...), $type->getTypes())).')';
        }
        if (!$type instanceof ReflectionNamedType) {
            return (string) $type;
        }
        $name = $type->isBuiltin() || in_array($type->getName(), ['self', 'static'], true) ? $type->getName() : '\\'.$type->getName();
        $nullable = $type->allowsNull() && !in_array($type->getName(), ['mixed', 'null'], true);

        return ($nullable ? '?' : '').$name;
    }
}
